# ─────────────────────────────────────────────
# LOW-LEVEL OLLAMA CALL
# ─────────────────────────────────────────────

def _call_ollama(model: str, system: str, user_prompt: str, temperature: float = 0.2) -> str:
    """
    Call the Ollama /api/generate endpoint.
    Returns the assembled response string.
    Raises httpx.HTTPError on failure.
    """
    payload = {
        "model": model,
        "system": system,
        "prompt": user_prompt,
        "stream": False,
        "options": {
            "temperature": temperature,
            "top_p": 0.9,
            "num_predict": 4096,
            "stop": [],
        },
    }
    try:
        with httpx.Client(timeout=TIMEOUT) as client:
            resp = client.post(f"{OLLAMA_BASE}/api/generate", json=payload)
            resp.raise_for_status()
            data = resp.json()
            return data.get("response", "").strip()
    except httpx.ConnectError:
        raise ConnectionError(
            f"Cannot connect to Ollama at {OLLAMA_BASE}. "
            "Ensure Ollama is running: `ollama serve`"
        )


def is_ollama_available() -> bool:
    """Quick health check — returns True if Ollama is reachable."""
    try:
        with httpx.Client(timeout=5) as client:
            r = client.get(f"{OLLAMA_BASE}/api/tags")
            return r.status_code == 200
    except Exception:
        return False


def list_available_models() -> list[str]:
    """Return list of locally available Ollama model names."""
    try:
        with httpx.Client(timeout=10) as client:
            r = client.get(f"{OLLAMA_BASE}/api/tags")
            r.raise_for_status()
            tags = r.json().get("models", [])
            return [t["name"] for t in tags]
    except Exception:
        return []


# ─────────────────────────────────────────────
# CODER FUNCTIONS (Qwen2.5-Coder)
